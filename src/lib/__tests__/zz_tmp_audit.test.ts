import { it } from 'vitest';
import { analyzeSolarReturn } from '../solarReturnAnalysis';
import { laurenNatal, laurenReturn } from '@/test/fixtures/solarReturnLauren';
import { generateDomainDeepDives } from '../solarReturnDomainDeepDive';
import { generatePowerPortrait } from '../solarReturnPowerPortrait';
import { calculateLifeDomainScores } from '../solarReturnLifeDomainScores';
import { generateIdentityShift } from '../solarReturnIdentityShift';
import { detectContradictions } from '../solarReturnContradictions';
import { generateActionGuidance } from '../solarReturnActionGuidance';
import { auditSolarReturnProse } from '../solarReturnProseBoundary';
import * as fs from 'fs';
it('audit', () => {
  const a = analyzeSolarReturn(laurenReturn, laurenNatal) as any;
  const out: any = {};
  const run = (k: string, f: () => unknown) => { try { out[k] = f(); } catch (e) { out[k] = 'ERR ' + e; } };
  run('domain', () => (generateDomainDeepDives as any)(a, laurenReturn, laurenNatal));
  run('power', () => (generatePowerPortrait as any)(laurenNatal, laurenReturn, a));
  run('scores', () => (calculateLifeDomainScores as any)(a, laurenReturn, laurenNatal));
  run('identity', () => (generateIdentityShift as any)(a, laurenReturn, laurenNatal));
  run('contra', () => (detectContradictions as any)(a, laurenReturn, laurenNatal));
  run('action', () => generateActionGuidance(a.planetSRHouses, laurenReturn.planets as any));
  run('analysisAudit', () => auditSolarReturnProse(a).slice(0, 40));
  fs.writeFileSync('/tmp/sr_audit.json', JSON.stringify(out, null, 1));
});
